from abc import ABC, abstractmethod

class ProductMixinLog:
    def __init__(self):
        print(f"Создан объект: {repr(self)}")

    def __repr__(self):
        name = getattr(self, 'name', 'неизвестно')
        description = getattr(self, 'description', 'нет описания')
        price = getattr(self, '_price', 0)
        quantity = getattr(self, 'quantity', 0)
        return f"{self.__class__.__name__}({name}, {description}, {price}, {quantity})"

class BaseProduct(ABC):

    @abstractmethod
    def __init__(self, name: str, description: str, price: float, quantity: int):
        self.quantity = quantity
        self.price = price
        self.description = description
        self.name = name

class Product(BaseProduct, ProductMixinLog):
    def __init__(self, name, description, price, quantity):
        BaseProduct.__init__(self, name, description, price, quantity)
        ProductMixinLog.__init__(self)

    @property
    def price(self) -> float:
        """Геттер для цены"""
        return self.__price

    @price.setter
    def price(self, new_price: float):
        """Сеттер для цены с проверкой"""
        if new_price <= 0:
            print("Цена не должна быть нулевая или отрицательная")
        else:
            self.__price = new_price

    @classmethod
    def new_product(cls, product_data) -> "Product":
        return cls(
            name=product_data["name"],
            description=product_data["description"],
            price=product_data["price"],
            quantity=product_data["quantity"],
        )

    @property
    def product_info(self) -> str:
        return f"{self.name}, {self.price} руб. Остаток: {self.quantity} шт."

    def __str__(self):
        return f"{self.name}, {self.price} руб. Остаток: {self.quantity} шт."

    def __add__(self, other):
        if type(self) != type(other):
            raise TypeError("Нельзя складывать товары разных классов")
        return self.price * self.quantity + other.price * other.quantity


class Category:
    name: str
    description: str
    __products: list[Product]
    category_count = 0
    product_count = 0

    def __init__(self, name, description, products):
        self.name = name
        self.description = description
        self.__products = products
        Category.category_count += 1
        Category.product_count += len(products)

    def add_product(self, product: Product):
        if not isinstance(product, Product):
            raise TypeError("Можно добавлять только объекты класса Product или его наследников")
        self.__products.append(product)
        Category.product_count += 1

    @property
    def products(self):
        return self.__products.copy()

    @property
    def total_quantity(self) -> int:
        return sum(product.quantity for product in self.__products)

    @property
    def products_info(self) -> str:
        return "\n".join(str(product) for product in self.__products)

    def __str__(self):
        return f"{self.name}, количество продуктов: {self.total_quantity} шт."


